"""ERA AI — fine-tuning config + runner (spec Section 13 + 26).

Generates a LoRA/QLoRA training config and an Ollama Modelfile that
registers the tuned result. The actual training runs via train_lora.py
(needs torch + transformers + peft, and realistically a GPU). If those
deps are absent, `runner` validates everything and reports a dry-run so
the pipeline is testable without a GPU.
"""
from __future__ import annotations

import json
import subprocess
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Dict, Optional


@dataclass
class TrainConfig:
    base_model: str            # HF id, e.g. "meta-llama/Llama-3.1-8B"
    dataset_dir: str
    output_dir: str
    worker_id: str
    epochs: int = 3
    learning_rate: float = 2e-4
    batch_size: int = 2
    gradient_accumulation: int = 8
    context_length: int = 2048
    lora_r: int = 16
    lora_alpha: int = 32
    lora_dropout: float = 0.05
    quantization: str = "qlora"   # "lora" | "qlora"

    def save(self, path: Path) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(asdict(self), indent=2), encoding="utf-8")
        return path


def preset(name: str, base_model: str, dataset_dir: str,
          output_dir: str, worker_id: str) -> TrainConfig:
    presets = {
        "quick":    dict(epochs=1, quantization="qlora", lora_r=8),
        "standard": dict(epochs=3, quantization="qlora", lora_r=16),
        "deep":     dict(epochs=5, quantization="qlora", lora_r=32),
    }
    kw = presets.get(name, presets["standard"])
    return TrainConfig(base_model=base_model, dataset_dir=dataset_dir,
                       output_dir=output_dir, worker_id=worker_id, **kw)


def deps_available() -> bool:
    for mod in ("torch", "transformers", "peft", "datasets"):
        try:
            __import__(mod)
        except ImportError:
            return False
    return True


def generate_modelfile(base_ollama_tag: str, adapter_dir: str,
                      identity: str, out_path: Path) -> Path:
    """Write an Ollama Modelfile that layers the tuned adapter + ERA identity."""
    content = f"""# Generated by ERA AI Training Studio
FROM {base_ollama_tag}

# LoRA adapter produced by fine-tuning
ADAPTER {adapter_dir}

SYSTEM \"\"\"
{identity}
\"\"\"

PARAMETER temperature 0.7
"""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    return out_path


def run_training(cfg: TrainConfig, root: Path) -> Dict:
    """Start training. Returns a status dict. Dry-run if deps missing."""
    ts = time.strftime("%Y%m%d-%H%M")
    out_dir = Path(cfg.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    cfg_path = cfg.save(out_dir / "train_config.json")

    if not deps_available():
        return {
            "status": "dry-run",
            "reason": "training deps not installed (torch/transformers/peft/datasets)",
            "config": str(cfg_path),
            "hint": "pip install torch transformers peft datasets accelerate bitsandbytes",
            "timestamp": ts,
        }

    script = root / "app" / "training" / "train_lora.py"
    proc = subprocess.run(
        [sys.executable, str(script), "--config", str(cfg_path)],
        capture_output=True, text=True,
    )
    return {
        "status": "done" if proc.returncode == 0 else "failed",
        "returncode": proc.returncode,
        "config": str(cfg_path),
        "stdout_tail": proc.stdout[-2000:],
        "stderr_tail": proc.stderr[-2000:],
        "timestamp": ts,
    }
